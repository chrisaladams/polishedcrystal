MACRO walking_mon
; A walking sprite (gfx/followers.asm): its first two frames are the mini and
; the icon, and the mask is made from it (a mask pointer of 0).
	db BANK(\1Walk)
	dw \1Walk, 0, \1Walk
ENDM

