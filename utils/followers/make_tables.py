#!/usr/bin/env python3
"""Hook the walking sprites in gfx/followers/ into the game.

For every gfx/followers/<name>.png (made by import_sheets.py):
- gfx/followers.asm gets a section with <Label>Walk, its compressed graphics;
- its mini, mask and icon are taken out of gfx/minis_icons.asm (any other
  form's graphics sharing that section get a section of their own);
- its entries in data/pokemon/mini_icon_pointers.asm become walking_mon, so
  the party menu, PC, trades and overworld draw its first two frames, and the
  follower walks with all six.
SHARE lists forms that use another form's walking sprite.

Safe to run again after adding sprites. Run from the repository root:
  python3 utils/followers/make_tables.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MINIS = os.path.join(ROOT, 'gfx', 'minis_icons.asm')
POINTERS = os.path.join(ROOT, 'data', 'pokemon', 'mini_icon_pointers.asm')
FOLLOWERS = os.path.join(ROOT, 'gfx', 'followers.asm')
SHARE = {
    'PikachuFly': 'Pikachu',  # its icon was Pikachu's; its mini only adds balloons
    # regional forms shaped like the regular form: its sprite in their own colours
    'RattataAlolan': 'Rattata', 'RaticateAlolan': 'Raticate', 'SandshrewAlolan': 'Sandshrew',
    'VulpixAlolan': 'Vulpix', 'NinetalesAlolan': 'Ninetales', 'DiglettAlolan': 'Diglett',
    'DugtrioAlolan': 'Dugtrio', 'MeowthAlolan': 'Meowth', 'PersianAlolan': 'Persian',
    'GeodudeAlolan': 'Geodude', 'GravelerAlolan': 'Graveler', 'SlowpokeGalarian': 'Slowpoke',
    'ArticunoGalarian': 'Articuno', 'MoltresGalarian': 'Moltres', 'ArcanineHisuian': 'Arcanine',
    'QwilfishHisuian': 'Qwilfish', 'SneaselHisuian': 'Sneasel', 'WooperPaldean': 'Wooper',
    'TaurosPaldean': 'Tauros', 'TaurosPaldeanFire': 'Tauros', 'TaurosPaldeanWater': 'Tauros',
    'UrsalunaBloodmoon': 'Ursaluna',
}
SECTION = re.compile(r'SECTION "(\w+) Mini Icon", ROMX\n(.*?)(?=\n\n|\nSECTION|\Z)', re.S)


def main():
    pngs = {f[:-4] for f in os.listdir(os.path.join(ROOT, 'gfx', 'followers')) if f.endswith('.png')}
    minis = open(MINIS).read()
    followers = open(FOLLOWERS).read() if os.path.exists(FOLLOWERS) else ''
    # label <-> file name, from the minis still there and the sprites already hooked up
    stem = dict(re.findall(r'^(\w+)Mini::\s+INCBIN "gfx/minis/(\w+)\.2bpp\.lzp"', minis, re.M))
    stem.update(re.findall(r'^(\w+)Walk::\s+INCBIN "gfx/followers/(\w+)\.2bpp\.lzp"', followers, re.M))
    walking = {label for label, s in stem.items() if s in pngs}

    # take the walking Pokemon out of the minis
    def shared(label):
        return SHARE.get(label) in walking

    def keep(m):
        name, body = m.group(1), m.group(2)
        if name not in walking and not shared(name):
            return m.group(0)
        others = []
        for label in re.findall(r'^(\w+?)(?:Mini|MiniMask|Icon)::', body, re.M):
            if label != name and label not in walking and not shared(label) and label not in others:
                others.append(label)
        out = []
        for o in others:
            s = re.search(r'^%sMini::\s+INCBIN "gfx/minis/(\w+)\.2bpp\.lzp"' % o, body, re.M).group(1)
            out.append(f'SECTION "{o} Mini Icon", ROMX\n'
                       f'{o}Mini::     INCBIN "gfx/minis/{s}.2bpp.lzp"\n'
                       f'{o}MiniMask:: INCBIN "gfx/minis/{s}_mask.1bpp.lzp"\n'
                       f'{o}Icon::     INCBIN "gfx/icons/{s}.2bpp.lzp"')
        return '\n\n'.join(out) if out else '\x00'
    minis = SECTION.sub(keep, minis)
    minis = re.sub(r'\n*\x00\n*', '\n\n', minis)
    open(MINIS, 'w').write(minis)

    # the pointer table
    ptrs = open(POINTERS).read()
    if 'MACRO walking_mon' not in ptrs:
        ptrs = ptrs.replace('MiniIconPointers:', '''MACRO walking_mon
; A walking sprite (gfx/followers.asm): its first two frames are the mini and
; the icon, and the mask is made from it (a mask pointer of 0).
	db BANK(\\1Walk)
	dw \\1Walk, 0, \\1Walk
ENDM

MiniIconPointers:''', 1)

    def entry(m):
        label = m.group(2)
        target = SHARE.get(label, label)
        if target in walking:
            return f'{m.group(1)}walking_mon {target}'
        return m.group(0)
    ptrs = re.sub(r'^(\s*)mini_icon (\w+)', entry, ptrs, flags=re.M)
    open(POINTERS, 'w').write(ptrs)

    # the walking sprites
    lines = ['; Walking sprites for following Pokemon, also used as their party menu minis',
             '; and overworld icons. Generated by utils/followers/make_tables.py from',
             '; gfx/followers/*.png; see gfx/followers/README.md for the credits.', '']
    for label in sorted(walking, key=lambda l: stem[l]):
        lines += [f'SECTION "{label} Walking Sprite", ROMX',
                  f'{label}Walk:: INCBIN "gfx/followers/{stem[label]}.2bpp.lzp"', '']
    open(FOLLOWERS, 'w').write('\n'.join(lines))
    print(f'{len(walking)} walking sprites hooked up')


if __name__ == '__main__':
    main()
